/**
 * PrintView — Print-optimized layout for research plans.
 *
 * Print styling is handled via CSS @media print in gencreator.css.
 * This component is kept as a potential standalone printable view
 * if needed in the future. Currently not used — the main plan view
 * handles print via CSS.
 */

import type { ResearchPlan } from '../lib/types.js';

interface PrintViewProps {
  plan: ResearchPlan;
}

export function PrintView({ plan }: PrintViewProps) {
  return (
    <div class="gc-print-view">
      <h1>Research Plan: {plan.ancestor.name}</h1>
      <p>
        {plan.ancestor.timePeriod} | {plan.ancestor.locations.join(', ')} |
        Generated {plan.generatedDate}
      </p>
      {plan.steps.map((step) => (
        <div key={step.priority}>
          <h2>
            {step.priority}. {step.title}
          </h2>
          <p>{step.rationale}</p>
          <p>
            Difficulty: {step.difficulty} | Databases:{' '}
            {step.databases.map((d) => d.name).join(', ')}
          </p>
        </div>
      ))}
      <p>
        <em>{plan.disclaimer}</em>
      </p>
      <p>
        <small>Generated by GenCreator — operationgrannyfiles.com</small>
      </p>
    </div>
  );
}
